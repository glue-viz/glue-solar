def test_no_new_import_of_a_private_name_from_another_module():
    root = Path(__file__).parents[1]  # glue_solar
    found = set()
    for path in root.rglob("*.py"):
        parts = path.relative_to(root.parent).with_suffix("").parts
        if "tests" in parts or parts[-1] == "conftest":
            continue
        module = ".".join(parts).removesuffix(".__init__")
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if isinstance(node, ast.ImportFrom):  # a relative import's module is under the importing one's package
                package = parts[: len(parts) - node.level] if node.level else ()
                source = ".".join([*package, node.module or ""]).rstrip(".")
                private = [alias.name for alias in node.names if alias.name.startswith("_") and alias.name[1:2] != "_"]
                if source.split(".")[0] == "glue_solar":
                    found |= {f"{module}:{source}:{name}" for name in private}
    new, gone = found - ALLOWED, ALLOWED - found
    assert not new, f"Make the name public in its module, or move it, rather than import it as private: {sorted(new)}"
    assert not gone, f"No longer imported, so remove it from ALLOWED: {sorted(gone)}"
